// يرجّع نسخة من العنصر بالنصوص الإنجليزية لو اللغة إنجليزي
export function localize(item, lang, kind = "product") {
  if (!item || lang !== "en") return item;
  const en = TABLES[kind]?.[item.id];
  const out = en ? { ...item, ...en } : { ...item };
  if (out.currency === "ج.م") out.currency = "EGP";
  return out;
}
